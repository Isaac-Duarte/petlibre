//! The page's TypeScript types, generated from the views that serve them.
//!
//! `src/web/packages/api/src/bench.gen.ts` is committed, so the web app builds
//! without Rust and a review sees contract changes. This test fails when it
//! is stale; `UPDATE_BINDINGS=1 cargo test -p wellfed-dashboard bindings`
//! rewrites it.

use std::path::PathBuf;

use ts_rs::{Config, TS};

use wellfed_formats::bench::banks::{Bank, Check, Content, Entry, Ledger, Source, Witness};
use wellfed_formats::bench::catalog::{CatalogEntry, Requirement, Tier};
use wellfed_formats::bench::live::{
    Activity, ActivityKind, BenchState, CancelState, CaptureView, ClockView, DeferredStop,
    FeederStatus, FeederView, JobEnd, JobView, Journal, JournalSource, Pause, Phase, ServerView,
    Session, StartRecord, Uart, UartRecord,
};
use wellfed_formats::bench::notes::{CardEvidence, Expect, Operator, Timer, TimerState, Verdict};
use wellfed_formats::bench::progress::{
    BenchCommand, Capture, Current, FlashTool, HistoryEntry, Outcome, Progress, RelayState, Step,
    StepState, Transfer, Unit,
};
use wellfed_formats::bench::run::{Evidence, RunRecord, ScenarioRecord, ScenarioVerdict};

/// One exported declaration, with its doc comment.
pub(super) fn decl<T: TS>(cfg: &Config) -> String {
    let docs = T::docs().unwrap_or_default();
    format!("{docs}export {}", T::decl(cfg))
}

fn generated() -> String {
    // Times, sizes and counts all fit a double; `bigint` would make the page
    // convert every one.
    let cfg = Config::new().with_large_int("number");

    let mut decls = vec![
        decl::<serde_json::Value>(&cfg),
        decl::<Outcome>(&cfg),
        decl::<StepState>(&cfg),
        decl::<Step>(&cfg),
        decl::<Unit>(&cfg),
        decl::<Progress>(&cfg),
        decl::<FlashTool>(&cfg),
        decl::<BenchCommand>(&cfg),
        decl::<HistoryEntry>(&cfg),
        decl::<RelayState>(&cfg),
        decl::<Tier>(&cfg),
        decl::<Requirement>(&cfg),
        decl::<CatalogEntry>(&cfg),
        decl::<Evidence>(&cfg),
        decl::<ScenarioVerdict>(&cfg),
        decl::<ScenarioRecord>(&cfg),
        decl::<RunRecord>(&cfg),
        // The bench server's live state.
        decl::<Capture>(&cfg),
        decl::<Transfer>(&cfg),
        decl::<Current>(&cfg),
        decl::<BenchState>(&cfg),
        decl::<ServerView>(&cfg),
        decl::<Phase>(&cfg),
        decl::<DeferredStop>(&cfg),
        decl::<JobView>(&cfg),
        decl::<CancelState>(&cfg),
        decl::<JobEnd>(&cfg),
        decl::<Activity>(&cfg),
        decl::<ActivityKind>(&cfg),
        decl::<Uart>(&cfg),
        decl::<FeederView>(&cfg),
        decl::<Session>(&cfg),
        decl::<Pause>(&cfg),
        decl::<FeederStatus>(&cfg),
        decl::<ClockView>(&cfg),
        decl::<Journal>(&cfg),
        decl::<JournalSource>(&cfg),
        decl::<CaptureView>(&cfg),
        decl::<StartRecord>(&cfg),
        decl::<UartRecord>(&cfg),
        decl::<Ledger>(&cfg),
        decl::<Bank>(&cfg),
        decl::<Entry>(&cfg),
        decl::<Content>(&cfg),
        decl::<Source>(&cfg),
        decl::<Check>(&cfg),
        decl::<Witness>(&cfg),
        decl::<Operator>(&cfg),
        decl::<Timer>(&cfg),
        decl::<Expect>(&cfg),
        decl::<TimerState>(&cfg),
        decl::<CardEvidence>(&cfg),
        decl::<Verdict>(&cfg),
    ];
    decls.extend(super::views::bindings(&cfg));
    decls.extend(super::runs::bindings(&cfg));
    decls.extend(super::stock::bindings(&cfg));

    let mut out = String::from(
        "// Generated by wellfed-dashboard's `bindings` test from the page's Rust views.\n\
         // Do not edit: change the Rust types, then run\n\
         // UPDATE_BINDINGS=1 cargo test -p wellfed-dashboard bindings\n\n",
    );
    for decl in decls {
        out += &decl;
        out += "\n\n";
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

#[test]
fn bindings_are_current() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../src/web/packages/api/src/bench.gen.ts");
    let want = generated();

    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        std::fs::write(&path, &want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "{} is stale; run UPDATE_BINDINGS=1 cargo test -p wellfed-dashboard bindings",
        path.display()
    );
}
